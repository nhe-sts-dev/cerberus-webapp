import { db } from "../src/server/db";
import { DeleteObjectCommand } from "@aws-sdk/client-s3";
import { s3Client } from "../src/server/s3"; 

async function main() {
  console.log("Starting comprehensive cleanup of all test data...");

  // 1. Target all test cameras used in our suite
  const testCameraIds = [
    "Test-Upload-Cam", 
    "Test-Inference-Cam", 
    "Test-Cam-A", 
    "Test-Cam-B", 
    "Test-Cam-C",
    "Test-Cam" // From the missing file test
  ];

  const testImages = await db.busImage.findMany({
    where: { cameraId: { in: testCameraIds } },
  });

  if (testImages.length > 0) {
    console.log(`Found ${testImages.length} test images. Deleting from Cloudflare R2...`);

    for (const image of testImages) {
      const urlParts = image.imageUrl.split("/");
      const folder = urlParts[urlParts.length - 2];
      const filename = urlParts[urlParts.length - 1];
      const objectKey = `${folder}/${filename}`;

      try {
        await s3Client.send(
          new DeleteObjectCommand({
            Bucket: process.env.R2_BUCKET_NAME,
            Key: objectKey,
          })
        );
      } catch (error) {
        console.error(`Failed to delete ${objectKey} from R2:`, error);
      }
    }
  }

  // 2. Clear Database - Must be done in relational order!
  console.log("Wiping test records from Neon DB...");

  // Delete InferenceLogs tied to our test model first
  await db.inferenceLog.deleteMany({
    where: { model: { name: "Integration-Test-Model" } }
  });

  // Delete the test model
  await db.modelRegistry.deleteMany({
    where: { name: "Integration-Test-Model" }
  });

  // Delete all transponder logs from the tests
  await db.transponderLog.deleteMany({
    where: {
      OR: [
        { gateId: "Test-Gate" },
        { gateId: "Batch-Upload" },
        { fleetNumber: { startsWith: "RACE-BUS" } }
      ]
    }
  });

  // Finally, delete the test BusImages
  const deletedImages = await db.busImage.deleteMany({
    where: { cameraId: { in: testCameraIds } }
  });

  console.log(`✅ Successfully deleted ${deletedImages.count} test images from DB.`);
  console.log("Cleanup complete!");
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await db.$disconnect();
  });























